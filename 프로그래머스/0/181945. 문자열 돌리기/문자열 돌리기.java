import java.util.Scanner;
import java.util.*;

public class Solution {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        String a = sc.next();
        
        char[] aCharArray = a.toCharArray();
        
        for(char c : aCharArray) {
            System.out.println(c);
        }
        
    }
}